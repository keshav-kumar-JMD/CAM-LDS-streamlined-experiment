def notebook(title,local=False):
    return {'nbformat':4,'nbformat_minor':5,'metadata':{
        'kernelspec':{'display_name':'CAM-LDS streamlined (Python 3.12)' if local else 'Python 3 (Colab GPU)',
                      'language':'python','name':'camlds-streamlined' if local else 'python3'},
        'language_info':{'name':'python'}},'cells':[{'cell_type':'markdown','metadata':{},'source':title.splitlines(True),'id':'introduction'}]}

def cell(nb,title,description,code,recovery,commands='',cost='No paid API requests.'):
    index=len(nb['cells'])
    text=f'## {title}\n\n{description}\n\n**Recovery / safe rerun:** {recovery}\n\n**Cost:** {cost}\n\n{commands}'
    nb['cells'].append({'cell_type':'markdown','metadata':{},'source':text.splitlines(True),'id':f'description-{index}'})
    nb['cells'].append({'cell_type':'code','metadata':{},'source':textwrap.dedent(code).strip().splitlines(True),
                       'outputs':[],'execution_count':None,'id':f'code-{index}'})

def save(nb,name):
    path=ROOT/'notebooks'/name;path.parent.mkdir(exist_ok=True)
    path.write_text(json.dumps(nb,indent=1,ensure_ascii=False)+'\n',encoding='utf-8')

